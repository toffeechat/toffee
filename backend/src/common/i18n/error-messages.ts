export function isErrorCode(value: unknown): value is ErrorCode {
  return typeof value === 'string' && Object.hasOwn(ERROR_MESSAGES, value);
}

export function translateError(code: ErrorCode, locale: string | null | undefined, params: ErrorParams = {}): string {
  const resolved = resolveLocale(locale);
  const text: Text = ERROR_MESSAGES[code][resolved];
  return typeof text === 'function' ? text(params, resolved) : text;
}
