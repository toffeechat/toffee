export type ErrorParams = Record<string, string | number>;
type Text = string | ((params: ErrorParams, locale: SupportedLocale) => string);

const INTL_LOCALE: Record<SupportedLocale, string> = {
  ko: 'ko-KR',
  th: 'th-TH',
  en: 'en-US',
  ja: 'ja-JP',
  'zh-Hans': 'zh-CN',
  'zh-Hant': 'zh-TW',
  vi: 'vi-VN',
  es: 'es-ES',
  'pt-BR': 'pt-BR',
};

/** 날짜 파라미터(ISO 문자열)를 받는 사람 언어의 태국 시간 표기로 */
function formatDate(value: string | number | undefined, locale: SupportedLocale, withTime = false): string {
  if (value === undefined) return '';
  return new Date(value).toLocaleString(INTL_LOCALE[locale], {
    timeZone: 'Asia/Bangkok',
    dateStyle: 'medium',
    ...(withTime ? { timeStyle: 'short' as const } : {}),
  });
}

